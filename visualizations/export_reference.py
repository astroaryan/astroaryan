"""Export notebook colours and numerical checks; Python is only needed for development."""
import argparse
import ast
import json
from itertools import product
from pathlib import Path

import matplotlib
import numpy as np
from matplotlib.colors import LinearSegmentedColormap


def notebook_assignments(path):
    notebook = json.loads(path.read_text())
    assignments = {}
    for cell in notebook['cells']:
        if cell['cell_type'] == 'code':
            for node in ast.parse(''.join(cell['source'])).body:
                if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                    assignments[node.targets[0].id] = node.value
    return assignments


def export_reference(notebook_directory, output_directory):
    # data wrangling
    planet = notebook_assignments(notebook_directory / 'planet_equilibrium_temperature.ipynb')
    blackbody = notebook_assignments(notebook_directory / 'blackbody_flambda.ipynb')
    radius_sun, au = (ast.literal_eval(planet[name]) for name in ['R_SUN', 'AU'])
    planck, light_speed, boltzmann = (ast.literal_eval(blackbody[name]) for name in ['h', 'c', 'k_B'])
    colour_knots = np.array(ast.literal_eval(blackbody['blackbody_colours'].args[0]))
    stellar = LinearSegmentedColormap.from_list('stellar_temperature', ast.literal_eval(planet['stellar_colors'].args[1]))
    coolwarm = matplotlib.colormaps['coolwarm']

    # calculations
    colours = {'matplotlibVersion': matplotlib.__version__, 'stellar': stellar(np.arange(stellar.N))[:, :3].tolist(),
               'coolwarm': coolwarm(np.arange(coolwarm.N))[:, :3].tolist(), 'blackbody': colour_knots.tolist()}
    cases = [(0.3, 3150, 0, 0.02, 0, 0), (0.3, 3150, 0, 0.02, 0.4, 0), (0.3, 3150, 0, 0.02, 0.4, np.pi)]
    cases += list(product([0.2, 3], [2500, 8000], [0, 1], [0.01, 30], [0, 0.75], [0, np.pi, 2 * np.pi]))
    cases += [(3, 8000, 0, 3 * radius_sun / au, 0, 0)]
    planet_cases = []
    for radius, temperature, albedo, distance, eccentricity, anomaly in cases:
        separation = distance * (1 - eccentricity**2) / (1 + eccentricity * np.cos(anomaly))
        equilibrium = temperature * np.sqrt(radius * radius_sun / (2 * separation * au)) * (1 - albedo)**0.25
        planet_cases.append({'input': dict(radius=radius, temperature=temperature, albedo=albedo, distance=distance, eccentricity=eccentricity, anomaly=anomaly),
                             'separation': separation, 'equilibrium': equilibrium, 'warning': bool(distance * (1 - eccentricity) * au <= radius * radius_sun), 'starColour': stellar((temperature - 2500) / 5500)[:3],
                             'planetColour': coolwarm(float(np.clip(equilibrium / 2000, 0, 1)))[:3]})
    blackbody_cases = []
    for temperature in [200, 588, 1000, 2500, 5990, 6000]:
        peak = 2897.8 / temperature
        wavelengths = np.linspace(0.1 * peak, 5 * peak, 500)
        wavelengths_m = wavelengths * 1e-6
        flux = np.pi * 2 * planck * light_speed**2 / wavelengths_m**5 / np.expm1(planck * light_speed / (wavelengths_m * boltzmann * temperature)) * 1e-6
        colour = [np.interp(temperature, colour_knots[:, 0], channel) for channel in colour_knots[:, 1:].T]
        blackbody_cases.append({'temperature': temperature, 'peak': peak, 'colour': colour, 'wavelengths': wavelengths.tolist(), 'flux': flux.tolist()})
    output_directory.mkdir(parents=True, exist_ok=True)
    (output_directory / 'colormaps.js').write_text('// Generated by export_reference.py from the source notebooks.\nwindow.AstroColormaps = ' + json.dumps(colours, separators=(',', ':')) + ';\n')
    references = {'matplotlibVersion': matplotlib.__version__, 'planet': planet_cases, 'blackbody': blackbody_cases}
    (output_directory / 'reference-values.json').write_text(json.dumps(references, separators=(',', ':')) + '\n')
    print(f'Exported Matplotlib {matplotlib.__version__}: {stellar.N} stellar colours, {coolwarm.N} coolwarm colours, {len(planet_cases)} planet cases, {len(blackbody_cases)} spectra.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('notebook_directory', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent)
    arguments = parser.parse_args()
    export_reference(arguments.notebook_directory, arguments.output)
